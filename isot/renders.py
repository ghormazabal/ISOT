def _secret_tools():
    from isot.ingest import PEM_RE, SECRET_KEYS, SECRET_PLACEHOLDER_RE

    return SECRET_KEYS, SECRET_PLACEHOLDER_RE, PEM_RE


def redact(value: Any) -> Any:
    """Copia sin valores secretos (claves tipo password/token/community → `<redacted>`)."""
    keys, placeholder, pem = _secret_tools()
    if isinstance(value, dict):
        out: dict[str, Any] = {}
        for key, item in value.items():
            if str(key).lower() in keys and isinstance(item, (str, int)) and str(item).strip():
                text = str(item).strip()
                out[str(key)] = text if placeholder.fullmatch(text) else "<redacted>"
            else:
                out[str(key)] = redact(item)
        return out
    if isinstance(value, list):
        return [redact(item) for item in value]
    if isinstance(value, str) and pem.search(value):
        return "<redacted>"
    return value


def scan_secrets(path: str, content: str) -> list[dict[str, Any]]:
    """Avisos de posibles secretos en una salida renderizada (no bloquea)."""
    _keys, placeholder, pem = _secret_tools()
    out: list[dict[str, Any]] = []
    for number, line in enumerate(content.splitlines(), start=1):
        if pem.search(line):
            out.append({"file": path, "line": number, "message": "clave privada PEM en la salida"})
            continue
        if line.lstrip().startswith("#"):
            continue
        match = SECRET_LINE_RE.search(line)
        if not match:
            continue
        value = match.group(2).strip().strip("\"'")
        if not value or placeholder.fullmatch(value) or value in {"<redacted>", "null", "~", "{}", "[]"}:
            continue
        out.append({"file": path, "line": number, "message": f"posible secreto en «{match.group(1)}»"})
    return out


