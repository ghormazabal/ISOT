@dataclass
class RenderResult:
    instance: str
    template: str
    version: str
    files: list[dict[str, Any]] = field(default_factory=list)
    errors: list[dict[str, Any]] = field(default_factory=list)
    warnings: list[dict[str, Any]] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors

    def to_dict(self, *, content: bool = True) -> dict[str, Any]:
        return {
            "instance": self.instance,
            "template": self.template,
            "version": self.version,
            "ok": self.ok,
            "count": len(self.files),
            "files": [{k: v for k, v in item.items() if content or k != "content"} for item in self.files],
            "errors": self.errors,
            "warnings": self.warnings,
        }


class _Reported(Exception):
    def __init__(self, info: dict[str, Any]) -> None:
        super().__init__(info.get("message"))
        self.info = info


def _wants_header(output: dict[str, Any], path: str) -> bool:
    if output.get("header") is not None:
        return bool(output.get("header"))
    return PurePosixPath(path).suffix.lower() in HEADER_SUFFIXES


def render_template(
    template: TemplateDef,
    builder: ContextBuilder,
    *,
    site: str,
    cluster: str | None = None,
    params: dict[str, Any] | None = None,
    instance_id: str = "preview",
) -> RenderResult:
    """Renderiza un template (del repo, de la herramienta o un borrador del editor).

    Nunca escribe a disco. Los errores llevan archivo y línea cuando se puede.
    """
    result = RenderResult(instance=instance_id, template=template.id, version=template.version)
    if template.errors:
        result.errors.extend(template.errors)
        return result
    spec = template.spec
    scope = template.scope
    merged = dict(spec.get("params") or {})
    merged.update(params or {})
    if scope == "cluster" and not cluster:
        result.errors.append(
            {"file": TEMPLATE_FILE, "line": None, "kind": "scope", "message": "scope: cluster necesita un clúster"}
        )
        return result
    try:
        variables = builder.variables(
            site,
            cluster,
            params=merged,
            instance={"id": instance_id, "site": site, "cluster": cluster},
            template={"id": template.id, "version": template.version, "scope": scope},
        )
    except RenderError as exc:
        result.errors.append({"file": TEMPLATE_FILE, "line": None, "kind": "context", "message": str(exc)})
        return result
    env = make_env(template.files)
    seen: set[str] = set()
    total = 0

    def evaluate_expr(expr: str, scope_vars: dict[str, Any], label: str) -> Any:
        try:
            return env.compile_expression(expr, undefined_to_none=False)(**scope_vars)
        except Exception as exc:  # noqa: BLE001 - se informa al usuario
            info = _error_info(exc, TEMPLATE_FILE)
            info.update({"file": TEMPLATE_FILE, "message": f"{label}: {info['message']}"})
            raise _Reported(info) from exc

    for index, output in enumerate(spec.get("outputs") or []):
        name = output["template"]
        label = f"outputs[{index}]"
        try:
            tmpl = env.get_template(name)
            path_tmpl = env.from_string(str(output.get("path")))
        except Exception as exc:  # noqa: BLE001
            result.errors.append(_error_info(exc, name, template.files))
            continue
        contexts: list[tuple[dict[str, Any], bool]] = []
        try:
            if output["mode"] == "per_item":
                expr = output.get("for_each") or spec.get("for_each") or "devices"
                items = evaluate_expr(str(expr), variables, f"{label}.for_each")
                if isinstance(items, dict):
                    items = list(items.values())
                if isinstance(items, (str, bytes)) or not hasattr(items, "__iter__"):
                    raise _Reported(
                        {"file": TEMPLATE_FILE, "line": None, "kind": "render", "message": f"{label}.for_each no devuelve una lista"}
                    )
                where = output.get("where") or spec.get("where")
                for position, item in enumerate(list(items)):
                    local = {**variables, "item": item, "items": None, "index": position}
                    if where and not evaluate_expr(str(where), local, f"{label}.where"):
                        continue
                    contexts.append((local, True))
            else:
                # single: si hay for_each (del output o del template), `items` es la lista filtrada.
                expr = output.get("for_each") or spec.get("for_each")
                items_list: list[Any] | None = None
                if expr:
                    raw_items = evaluate_expr(str(expr), variables, f"{label}.for_each")
                    where = output.get("where") or spec.get("where")
                    items_list = [
                        item
                        for position, item in enumerate(list(raw_items or []))
                        if not where or evaluate_expr(str(where), {**variables, "item": item, "index": position}, f"{label}.where")
                    ]
                contexts.append(({**variables, "item": None, "items": items_list, "index": 0}, False))
        except _Reported as rep:
            result.errors.append(rep.info)
            continue
        for local, per_item in contexts:
            try:
                rel = safe_rel_dir(path_tmpl.render(**local).strip(), f"{label}.path")
            except RenderError as exc:
                result.errors.append({"file": TEMPLATE_FILE, "line": None, "kind": "path", "message": str(exc)})
                continue
            except Exception as exc:  # noqa: BLE001
                info = _error_info(exc, TEMPLATE_FILE)
                info.update({"file": TEMPLATE_FILE, "message": f"{label}.path: {info['message']}"})
                result.errors.append(info)
                continue
            if PurePosixPath(rel).name == SIDECAR:
                result.errors.append({"file": TEMPLATE_FILE, "line": None, "kind": "path", "message": f"{SIDECAR} es un nombre reservado"})
                continue
            if rel in seen:
                result.errors.append(
                    {
                        "file": TEMPLATE_FILE,
                        "line": None,
                        "kind": "path",
                        "message": f"{label}: ruta de salida duplicada {rel} (usa una variable del item en path, o mode: single)",
                    }
                )
                continue
            try:
                content = tmpl.render(**local)
            except Exception as exc:  # noqa: BLE001
                info = _error_info(exc, name, template.files)
                if per_item:
                    info["item"] = rel
                result.errors.append(info)
                continue
            content = content.rstrip("\n") + "\n" if content.strip() else ""
            if _wants_header(output, rel):
                content = f"# {HEADER}\n# template: {template.id}@{template.version} · instance: {instance_id}\n" + content
            total += len(content.encode("utf-8"))
            if total > MAX_OUTPUT_BYTES or len(seen) >= MAX_FILES:
                result.errors.append({"file": name, "line": None, "kind": "limit", "message": "salida demasiado grande (límite de archivos/bytes)"})
                return result
            seen.add(rel)
            result.files.append({"path": rel, "content": content, "output": index, "source": name, "mode": output["mode"]})
            result.warnings.extend({**w, "kind": "secret"} for w in scan_secrets(rel, content))
    result.files.sort(key=lambda item: item["path"])
    return result


def render_instance(root: Path, builder: ContextBuilder, instance: Instance) -> tuple[RenderResult, TemplateDef | None]:
    template = find_template(root, instance.template)
    if template is None:
        result = RenderResult(instance=instance.id, template=instance.template, version="?")
        result.errors.append(
            {"file": instance.source, "line": None, "kind": "missing", "message": f"no existe el template de render {instance.template!r}"}
        )
        return result, None
    result = render_template(
        template, builder, site=instance.site, cluster=instance.cluster, params=instance.params, instance_id=instance.id
    )
    return result, template


def sidecar_content(template: TemplateDef | None, instance: Instance, files: list[dict[str, Any]], source_commit: str | None) -> str:
    payload = {
        "generated_by": "ISoT",
        "notice": HEADER,
        "context_version": CONTEXT_VERSION,
        "template": f"{instance.template}@{template.version if template else '?'}",
        "template_source": template.source if template else None,
        "instance": instance.id,
        "site": instance.site,
        "cluster": instance.cluster,
        "source_commit": source_commit,
        "files": [{"path": f["path"], "sha256": hashlib.sha256(f["content"].encode("utf-8")).hexdigest()} for f in files],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


