class RenderService:
    """Templates, instancias, render y diff contra carpetas del mismo repositorio de datos."""

    def __init__(self, root: Path, ctx: Any | None = None, *, git_root: Path | None = None) -> None:
        self.root = root
        # Repo git real (para leer la carpeta destino en otra ref cuando `root` es un árbol materializado).
        self.git_root = git_root or root
        self._ctx = ctx
        self.config = load_render_config(root)
        self.repo_error: str | None = None
        try:
            check_target_path(root, self.config.target_dir)
        except RenderError as exc:
            self.repo_error = str(exc)
        self._builder: ContextBuilder | None = None
        self._results: dict[str, tuple[RenderResult, TemplateDef | None]] = {}

    @property
    def builder(self) -> ContextBuilder:
        if self._builder is None:
            if self._ctx is None:
                from isot.rules.context import load_context

                self._ctx = load_context(self.root)
            self._builder = ContextBuilder(self._ctx)
        return self._builder

    def instances(self, *, enabled_only: bool = True) -> list[Instance]:
        return [i for i in self.config.instances if i.enabled or not enabled_only]

    def instance(self, instance_id: str) -> Instance | None:
        return next((i for i in self.config.instances if i.id == instance_id), None)

    def folder_for(self, instance: Instance) -> tuple[str | None, str | None]:
        """(carpeta destino, error) de una instancia; valida traversal, symlinks y la instalación de ISoT."""
        try:
            folder = target_folder(self.config, instance)
            if self.repo_error:
                return folder, self.repo_error
            check_target_path(self.root, folder)
            return folder, None
        except RenderError as exc:
            return None, str(exc)

    def render(self, instance: Instance) -> tuple[RenderResult, TemplateDef | None]:
        if instance.id not in self._results:
            self._results[instance.id] = render_instance(self.root, self.builder, instance)
        return self._results[instance.id]

    def target_diff(self, *, instance_id: str | None = None, ref: str | None = None) -> dict[str, Any]:
        """Render actual vs lo que ya existe en la carpeta destino (mismo repo), por instancia y archivo."""
        members = self.instances()
        if instance_id:
            members = [i for i in members if i.id == instance_id]
        folders = {i.id: self.folder_for(i) for i in self.instances()}
        all_dirs = [f for f, _ in folders.values() if f]
        payload_instances = []
        totals = count_status([])
        for inst in members:
            result, template = self.render(inst)
            rendered = {f["path"]: f["content"] for f in result.files}
            folder, error = folders[inst.id]
            entry: dict[str, Any] = {
                "id": inst.id,
                "template": inst.template,
                "version": result.version,
                "site": inst.site,
                "cluster": inst.cluster,
                "dir": folder,
                "errors": result.errors,
                "warnings": result.warnings,
                "files": [],
                "counts": count_status([]),
                "skipped": [],
                "sidecar": None,
            }
            if error or not folder:
                entry["target_error"] = error or "carpeta destino inválida"
                payload_instances.append(entry)
                continue
            try:
                existing, skipped = read_target_tree(self.git_root, folder, ref)
            except Exception as exc:  # noqa: BLE001 - ref inválida, ruta fuera…
                entry["target_error"] = str(exc)
                payload_instances.append(entry)
                continue
            nested = [d[len(folder) + 1 :] for d in all_dirs if d != folder and d.startswith(folder + "/")]
            files = diff_files(rendered, existing, nested=nested) if result.ok else []
            for item in files:
                item["target_path"] = f"{folder}/{item['path']}"
            sidecar_text = existing.get(SIDECAR)
            if sidecar_text:
                try:
                    entry["sidecar"] = json.loads(sidecar_text)
                except ValueError:
                    entry["sidecar"] = {"error": "sidecar ilegible"}
            entry["files"] = files
            entry["skipped"] = skipped
            entry["counts"] = count_status(files)
            entry["in_sync"] = result.ok and all(f["status"] == "unchanged" for f in files)
            recorded = (entry["sidecar"] or {}).get("template") if isinstance(entry["sidecar"], dict) else None
            entry["stale"] = bool(recorded) and recorded != f"{inst.template}@{result.version}"
            for key, value in entry["counts"].items():
                totals[key] += value
            payload_instances.append(entry)
        return {
            "target_dir": self.config.target_dir,
            "error": self.repo_error,
            "ref": ref,
            "instances": payload_instances,
            "counts": totals,
            "in_sync": sum(1 for i in payload_instances if i.get("in_sync")),
            "drift": sum(1 for i in payload_instances if not i.get("in_sync")),
        }

    def apply_plan(
        self, instance_ids: Iterable[str] | None = None, *, prune: bool = False, source_commit: str | None = None
    ) -> dict[str, Any]:
        """Archivos a escribir/borrar en el mismo repo de datos (rutas relativas a su raíz)."""
        if self.repo_error:
            raise RenderError(self.repo_error)
        diff = self.target_diff()
        wanted = set(instance_ids) if instance_ids else None
        writes: dict[str, str] = {}
        deletes: list[str] = []
        skipped: list[str] = []
        folders: list[str] = []
        for entry in diff["instances"]:
            if wanted is not None and entry["id"] not in wanted:
                continue
            if entry["errors"] or entry.get("target_error") or not entry["dir"]:
                skipped.append(entry["id"])
                continue
            inst = self.instance(entry["id"])
            result, template = self.render(inst)  # type: ignore[arg-type]
            base = entry["dir"]
            folders.append(base)
            changed = False
            for item in entry["files"]:
                if item["status"] in {"new", "modified"}:
                    writes[f"{base}/{item['path']}"] = item["after"]
                    changed = True
                elif item["status"] == "orphaned" and prune:
                    deletes.append(f"{base}/{item['path']}")
                    changed = True
            if changed or not entry.get("sidecar"):
                writes[f"{base}/{SIDECAR}"] = sidecar_content(template, inst, result.files, source_commit)  # type: ignore[arg-type]
        return {"writes": writes, "deletes": deletes, "skipped": skipped, "folders": folders, "diff": diff}

    def dashboard(self) -> dict[str, Any]:
        templates = list_templates(self.root)
        per_site: dict[str, dict[str, int]] = {}
        per_cluster: dict[str, dict[str, int]] = {}
        files = errors = warnings = 0
        rows = []
        for inst in self.instances(enabled_only=False):
            result, template = self.render(inst) if inst.enabled else (RenderResult(inst.id, inst.template, "?"), None)
            folder, folder_error = self.folder_for(inst)
            files += len(result.files)
            errors += len(result.errors)
            warnings += len(result.warnings)
            for bucket, key in ((per_site, inst.site), (per_cluster, f"{inst.site}/{inst.cluster}" if inst.cluster else None)):
                if key is None:
                    continue
                slot = bucket.setdefault(key, {"instances": 0, "files": 0, "errors": 0})
                slot["instances"] += 1
                slot["files"] += len(result.files)
                slot["errors"] += 1 if result.errors else 0
            rows.append(
                {
                    **inst.to_dict(),
                    "folder": folder,
                    "folder_error": folder_error,
                    "template_source": template.source if template else None,
                    "version": result.version,
                    "files": len(result.files),
                    "errors": result.errors[:5],
                    "error_count": len(result.errors),
                    "warning_count": len(result.warnings),
                    "status": "disabled" if not inst.enabled else ("error" if result.errors else "ok"),
                }
            )
        diff = self.target_diff()
        drift = {
            "in_sync": diff["in_sync"],
            "drift": diff["drift"],
            "stale": sum(1 for i in diff["instances"] if i.get("stale")),
            "counts": diff["counts"],
            "error": self.repo_error,
        }
        return {
            "context_version": CONTEXT_VERSION,
            "templates": {
                "total": len([t for t in templates if t.source != "bundled-overridden"]),
                "repo": sum(1 for t in templates if t.source == "repo"),
                "bundled": sum(1 for t in templates if t.source.startswith("bundled")),
                "invalid": sum(1 for t in templates if t.errors),
            },
            "instances": {
                "total": len(rows),
                "enabled": sum(1 for r in rows if r["enabled"]),
                "ok": sum(1 for r in rows if r["status"] == "ok"),
                "error": sum(1 for r in rows if r["status"] == "error"),
            },
            "files": files,
            "errors": errors,
            "warnings": warnings,
            "per_site": per_site,
            "per_cluster": per_cluster,
            "drift": drift,
            "rows": rows,
            "config": {
                "path": self.config.path,
                "exists": self.config.exists,
                "target_dir": self.config.target_dir,
                "errors": self.config.errors,
            },
        }


