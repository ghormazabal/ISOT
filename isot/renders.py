def commit_files(
    repo: Path,
    writes: dict[str, str],
    deletes: Iterable[str],
    description: str,
    *,
    allowed_prefix: str | Iterable[str] | None = None,
    branch: str | None = None,
    branch_label: str | None = None,
) -> dict[str, Any]:
    """Escribe/borra archivos en una rama `wizard/…` del repo y la confirma.

    Mismo patrón que los wizards: nunca en main ni en la rama actual; si algo
    falla se descarta la rama. `branch` continúa una rama `wizard/…` existente.
    `allowed_prefix` (una carpeta o varias) limita todas las rutas a esas carpetas.
    """
    from isot.gitdiff import git, is_git_toplevel
    from isot.wizard import PROTECTED_BRANCHES, SAFE_BRANCH, WizardError, current_branch, unique_wizard_branch

    deletes = list(deletes)
    if not writes and not deletes:
        raise WizardError("no hay cambios que escribir")
    root = repo.resolve()
    if inside_tool(root):
        raise WizardError("no se escribe en la instalación de ISoT: los renders van al propio repo de datos")
    if not is_git_toplevel(repo):
        raise WizardError("el repo de datos no es la raíz de un repositorio git")
    prefixes = [allowed_prefix] if isinstance(allowed_prefix, str) else list(allowed_prefix or [])
    for rel in [*writes, *deletes]:
        try:
            safe_rel_dir(rel, "archivo")
        except RenderError as exc:
            raise WizardError(str(exc)) from exc
        if prefixes and not any(rel.startswith(p.rstrip("/") + "/") for p in prefixes):
            raise WizardError(f"ruta fuera del destino: {rel}")
        parent = (root / rel).parent
        if parent.exists() and not parent.resolve().is_relative_to(root):
            raise WizardError(f"ruta fuera del repositorio (symlink): {rel}")
    if git(repo, ["status", "--porcelain"]).stdout.strip():
        raise WizardError("working tree sucio; confirma o descarta cambios antes de escribir")
    branch_now = current_branch(repo)
    if branch:
        if not branch.startswith("wizard/") or not SAFE_BRANCH.fullmatch(branch) or branch in PROTECTED_BRANCHES:
            raise WizardError("solo se continúan ramas wizard/…")
        if git(repo, ["rev-parse", "--verify", "--quiet", f"refs/heads/{branch}"]).returncode != 0:
            raise WizardError(f"no existe la rama {branch}")
        if branch == branch_now:
            raise WizardError("la rama elegida es la rama actual del repo; vuelve a main antes")
        target_branch, created = branch, False
        proc = git(repo, ["checkout", branch])
    else:
        target_branch, created = unique_wizard_branch(repo, branch_label or description), True
        if target_branch in PROTECTED_BRANCHES or target_branch == branch_now:
            raise WizardError("la rama destino no puede ser main ni la rama actual")
        proc = git(repo, ["checkout", "-b", target_branch])
    if proc.returncode != 0:
        raise WizardError((proc.stderr or proc.stdout).decode("utf-8", "replace") or "no se pudo cambiar de rama")

    def rollback() -> None:
        git(repo, ["reset", "--hard", "HEAD"])
        git(repo, ["clean", "-fd"])
        git(repo, ["checkout", branch_now])
        if created:
            git(repo, ["branch", "-D", target_branch])

    try:
        for rel, content in writes.items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.parent.resolve().is_relative_to(root) or path.is_symlink():
                raise WizardError(f"ruta fuera del repositorio (symlink): {rel}")
            path.write_text(content, encoding="utf-8")
        for rel in deletes:
            path = root / rel
            if path.is_file() and not path.is_symlink() and path.resolve().is_relative_to(root):
                path.unlink()
        # El índice (incluidos manifest-templates/, renders.yaml y rendered/) va en el mismo commit.
        from isot.indexer import write_indexes

        write_indexes(root)
        git(repo, ["add", "-A"])
        if not git(repo, ["status", "--porcelain"]).stdout.strip():
            rollback()
            raise WizardError("sin cambios: la rama ya tiene ese contenido")
        has_identity = git(repo, ["config", "user.email"]).returncode == 0
        identity = [] if has_identity else ["-c", "user.name=ISoT Wizard", "-c", "user.email=isot@example.net"]
        message = f"wizard: {description}"
        committed = git(repo, [*identity, "commit", "-m", message])
        if committed.returncode != 0:
            detail = (committed.stderr or committed.stdout).decode("utf-8", "replace")
            rollback()
            raise WizardError(detail or "git commit falló")
        sha = git(repo, ["rev-parse", "HEAD"]).stdout.decode("utf-8").strip()
        git(repo, ["checkout", branch_now])
        return {
            "ok": True,
            "branch": target_branch,
            "created": created,
            "sha": sha,
            "short": sha[:7],
            "base": branch_now,
            "message": message,
            "files": sorted([*writes, *deletes]),
        }
    except WizardError:
        raise
    except Exception as exc:  # noqa: BLE001
        rollback()
        raise WizardError(str(exc)) from exc


def head_sha(repo: Path) -> str | None:
    from isot.gitdiff import git

    proc = git(repo, ["rev-parse", "HEAD"])
    return proc.stdout.decode("utf-8").strip() if proc.returncode == 0 else None


def file_diffs(root: Path, writes: dict[str, str], deletes: Iterable[str] = ()) -> list[dict[str, Any]]:
    """Diff unificado de cada archivo propuesto contra el working tree del repo."""
    out = []
    for rel, content in sorted(writes.items()):
        path = root / rel
        before = path.read_text(encoding="utf-8") if path.is_file() and not path.is_symlink() else None
        out.append(
            {
                "path": rel,
                "status": "new" if before is None else ("unchanged" if before == content else "modified"),
                "diff": unified(rel, before, content),
                "content": content,
            }
        )
    for rel in sorted(deletes):
        path = root / rel
        before = path.read_text(encoding="utf-8") if path.is_file() and not path.is_symlink() else ""
        out.append({"path": rel, "status": "deleted", "diff": unified(rel, before, None), "content": None})
    return out
