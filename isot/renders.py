@dataclass
class Instance:
    id: str
    template: str
    site: str
    cluster: str | None = None
    target_dir: str | None = None  # carpeta destino propia (mismo repo); None = la global
    dir: str | None = None
    params: dict[str, Any] = field(default_factory=dict)
    enabled: bool = True
    description: str | None = None
    source: str = RENDERS_FILE

    def default_dir(self) -> str:
        return f"{self.site}/{self.cluster or 'site'}/{self.template}"

    @property
    def out_dir(self) -> str:
        return (self.dir or self.default_dir()).strip("/")

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "template": self.template,
            "site": self.site,
            "cluster": self.cluster,
            "target_dir": self.target_dir,
            "dir": self.out_dir,
            "dir_explicit": bool(self.dir),
            "params": self.params,
            "enabled": self.enabled,
            "description": self.description,
            "source": self.source,
        }


@dataclass
class RenderConfig:
    path: str
    exists: bool
    target_dir: str = DEFAULT_TARGET_DIR
    instances: list[Instance] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    raw: dict[str, Any] = field(default_factory=dict)
    text: str = ""


def safe_rel_dir(value: Any, where: str) -> str:
    """Ruta relativa POSIX: sin `..`, sin `/` inicial, sin `.git` y con segmentos seguros."""
    raw = str(value or "").strip()
    if raw.startswith("/") or raw.startswith("~") or "\\" in raw:
        raise RenderError(f"{where}: debe ser una ruta relativa dentro del repositorio: {raw!r}")
    text = raw.strip("/")
    if not text:
        raise RenderError(f"{where}: ruta vacía")
    for part in text.split("/"):
        if part in {"", ".", ".."} or not (SAFE_SEGMENT.fullmatch(part) or part == SIDECAR):
            raise RenderError(f"{where}: segmento inválido {part!r} en {text!r}")
    if text.split("/")[0] == ".git":
        raise RenderError(f"{where}: no se puede escribir en .git")
    return text


def _parse_instances(raw_list: Any, where: str, default_site: str | None, errors: list[str]) -> list[Instance]:
    out: list[Instance] = []
    if raw_list is None:
        return out
    if not isinstance(raw_list, list):
        errors.append(f"{where}: instances debe ser una lista")
        return out
    for index, raw in enumerate(raw_list):
        label = f"{where}: instances[{index}]"
        if not isinstance(raw, dict):
            errors.append(f"{label} debe ser un mapa")
            continue
        if "target" in raw:
            errors.append(f"{label}: «target» ya no existe; usa target_dir (una carpeta de este mismo repo)")
        unknown = sorted(set(raw) - INSTANCE_KEYS - REMOVED_KEYS)
        if unknown:
            errors.append(f"{label}: claves desconocidas {', '.join(unknown)}")
        template = str(raw.get("template") or "").strip()
        site = str(raw.get("site") or default_site or "").strip()
        if not template or not site:
            errors.append(f"{label}: faltan template y/o site")
            continue
        inst_id = str(raw.get("id") or "").strip() or f"{site}-{raw.get('cluster') or 'site'}-{template}"
        if not SAFE_ID.fullmatch(inst_id):
            errors.append(f"{label}: id inválido {inst_id!r}")
            continue
        params = raw.get("params") or {}
        if not isinstance(params, dict):
            errors.append(f"{label}: params debe ser un mapa")
            params = {}
        directory = None
        target_dir = None
        try:
            if raw.get("dir"):
                directory = safe_rel_dir(raw.get("dir"), f"{label}.dir")
            if raw.get("target_dir"):
                target_dir = safe_rel_dir(raw.get("target_dir"), f"{label}.target_dir")
        except RenderError as exc:
            errors.append(str(exc))
            continue
        out.append(
            Instance(
                id=inst_id,
                template=template,
                site=site,
                cluster=_text(raw.get("cluster")),
                target_dir=target_dir,
                dir=directory,
                params=params,
                enabled=raw.get("enabled", True) is not False,
                description=_text(raw.get("description")),
                source=where,
            )
        )
    return out


def load_render_config(root: Path) -> RenderConfig:
    """`renders.yaml` de la raíz (carpeta destino e instancias) + `sites/<id>/renders.yaml`."""
    from isot.inventory import load_catalog

    path = root / RENDERS_FILE
    cfg = RenderConfig(path=RENDERS_FILE, exists=path.is_file())
    data: dict[str, Any] = {}
    if cfg.exists:
        cfg.text = path.read_text(encoding="utf-8")
        try:
            loaded = yaml.safe_load(cfg.text)
            if loaded is None:
                loaded = {}
            if isinstance(loaded, dict):
                data = loaded
            else:
                cfg.errors.append(f"{RENDERS_FILE}: debe ser un mapa YAML")
        except yaml.YAMLError as exc:
            cfg.errors.append(f"{RENDERS_FILE}: YAML inválido: {exc}")
    cfg.raw = data
    removed = sorted(set(data) & REMOVED_KEYS)
    if removed:
        cfg.errors.append(
            f"{RENDERS_FILE}: {', '.join(removed)} ya no existe(n): los renders solo se escriben en "
            "carpetas de este mismo repositorio (target_dir global o por instancia)"
        )
    unknown = sorted(set(data) - RENDERS_KEYS - REMOVED_KEYS)
    if unknown:
        cfg.errors.append(f"{RENDERS_FILE}: claves desconocidas {', '.join(unknown)}")
    try:
        cfg.target_dir = safe_rel_dir(data.get("target_dir") or DEFAULT_TARGET_DIR, f"{RENDERS_FILE}: target_dir")
    except RenderError as exc:
        cfg.errors.append(str(exc))
    cfg.instances = _parse_instances(data.get("instances"), RENDERS_FILE, None, cfg.errors)
    sites, _ = load_catalog(root)
    for site in sites:
        site_file = site.root / RENDERS_FILE
        if not site_file.is_file():
            continue
        rel = f"{site.rel_path}/{RENDERS_FILE}"
        try:
            loaded = yaml.safe_load(site_file.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as exc:
            cfg.errors.append(f"{rel}: YAML inválido: {exc}")
            continue
        if not isinstance(loaded, dict):
            cfg.errors.append(f"{rel}: debe ser un mapa con instances")
            continue
        cfg.instances.extend(_parse_instances(loaded.get("instances"), rel, site.id, cfg.errors))
    ids = [i.id for i in cfg.instances]
    for dup in sorted({i for i in ids if ids.count(i) > 1}):
        cfg.errors.append(f"instancia duplicada: {dup}")
    return cfg


def inside_tool(path: Path) -> bool:
    """¿`path` está dentro de la instalación de ISoT (o la contiene)?"""
    resolved = path.resolve()
    tool = tool_root().resolve()
    return resolved == tool or resolved.is_relative_to(tool) or tool.is_relative_to(resolved)


def check_target_path(repo_root: Path, rel_dir: str) -> Path:
    """Valida que `repo_root/rel_dir` quede dentro del repo (también tras symlinks)
    y fuera de la instalación de ISoT. Devuelve la ruta resuelta."""
    rel = safe_rel_dir(rel_dir, "dir")
    root = repo_root.resolve()
    if inside_tool(root):
        raise RenderError(
            "el repositorio está dentro de la instalación de ISoT; los renders solo se escriben "
            "en una carpeta del propio repositorio de datos"
        )
    resolved = (root / rel).resolve()
    if not resolved.is_relative_to(root):
        raise RenderError(f"el destino {rel} sale del repositorio (symlink o ruta)")
    if inside_tool(resolved):
        raise RenderError("el destino resuelve dentro de la instalación de ISoT")
    return resolved


def target_folder(cfg: RenderConfig, instance: Instance) -> str:
    """Carpeta (relativa a la raíz del repo de datos) donde vive la salida de una instancia."""
    return safe_rel_dir(f"{instance.target_dir or cfg.target_dir}/{instance.out_dir}", f"{instance.id}: carpeta destino")


