def unified(path: str, before: str | None, after: str | None) -> str:
    return "".join(
        difflib.unified_diff(
            (before or "").splitlines(keepends=True),
            (after or "").splitlines(keepends=True),
            fromfile=f"a/{path}" if before is not None else "/dev/null",
            tofile=f"b/{path}" if after is not None else "/dev/null",
        )
    )


def read_target_tree(root: Path, rel_dir: str, ref: str | None = None) -> tuple[dict[str, str], list[str]]:
    """{ruta relativa a `rel_dir`: contenido} de lo que ya existe en esa carpeta del repo de datos.

    Sin `ref` lee el working tree sin seguir symlinks; con `ref`, lo confirmado
    en esa rama o commit del mismo repositorio.
    """
    full_rel = safe_rel_dir(rel_dir, "dir")
    out: dict[str, str] = {}
    skipped: list[str] = []
    if ref:
        from isot.gitdiff import git, resolve_sha, validate_ref

        check_target_path(root, full_rel)
        sha = resolve_sha(root, validate_ref(ref))
        listing = git(root, ["ls-tree", "-r", "-z", "--full-tree", sha, "--", full_rel])
        if listing.returncode != 0:
            raise RenderError((listing.stderr or b"").decode("utf-8", "replace") or "git ls-tree falló")
        for entry in listing.stdout.decode("utf-8", "replace").split("\0"):
            if not entry:
                continue
            meta, _, path = entry.partition("\t")
            mode, kind, blob = meta.split()
            if not path.startswith(full_rel + "/"):
                continue
            rel = path[len(full_rel) + 1 :]
            if mode == "120000" or kind != "blob":
                skipped.append(rel)
                continue
            shown = git(root, ["cat-file", "blob", blob])
            try:
                out[rel] = shown.stdout.decode("utf-8")
            except UnicodeDecodeError:
                skipped.append(rel)
        return out, skipped
    base = check_target_path(root, full_rel)
    if not base.exists():
        return out, skipped
    root_resolved = root.resolve()
    for dirpath, dirnames, filenames in os.walk(base, followlinks=False):
        current = Path(dirpath)
        keep = []
        for name in sorted(dirnames):
            child = current / name
            if child.is_symlink() or name == ".git":
                skipped.append(child.relative_to(base).as_posix())
            else:
                keep.append(name)
        dirnames[:] = keep
        for name in sorted(filenames):
            child = current / name
            rel = child.relative_to(base).as_posix()
            if child.is_symlink() or not child.resolve().is_relative_to(root_resolved) or child.stat().st_size > MAX_OUTPUT_BYTES:
                skipped.append(rel)
                continue
            try:
                out[rel] = child.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                skipped.append(rel)
        if len(out) > MAX_FILES:
            break
    return out, skipped


def diff_files(rendered: dict[str, str], existing: dict[str, str], *, nested: Iterable[str] = ()) -> list[dict[str, Any]]:
    """Estado por archivo: new / modified / unchanged / orphaned (existe en el destino y no se renderiza).

    `nested`: subcarpetas que pertenecen a otras instancias (no cuentan como huérfanas).
    """
    prefixes = [n.strip("/") + "/" for n in nested if n]
    out: list[dict[str, Any]] = []
    for path in sorted(set(rendered) | set(existing)):
        if PurePosixPath(path).name == SIDECAR:
            continue
        if path not in rendered and any(path.startswith(prefix) for prefix in prefixes):
            continue
        before, after = existing.get(path), rendered.get(path)
        if before is None:
            status = "new"
        elif after is None:
            status = "orphaned"
        elif before == after:
            status = "unchanged"
        else:
            status = "modified"
        out.append(
            {
                "path": path,
                "status": status,
                "before": before,
                "after": after,
                "diff": "" if status == "unchanged" else unified(path, before, after),
            }
        )
    return out


COMPARE_STATUS = {"new": "added", "orphaned": "removed", "modified": "modified", "unchanged": "unchanged"}


def compare_outputs(base_root: Path, head_root: Path, *, instance_id: str | None = None) -> dict[str, Any]:
    """Salida renderizada en base vs en head (dos árboles del mismo repo, p.ej. `local` y un commit).

    Renderiza en memoria cada instancia en ambos lados y compara por ruta final
    (`<carpeta destino>/<archivo>`): added / removed / modified / unchanged.
    """

    def outputs(root: Path) -> tuple[dict[str, tuple[str, str]], dict[str, dict[str, Any]], list[str]]:
        svc = RenderService(root)
        files: dict[str, tuple[str, str]] = {}
        meta: dict[str, dict[str, Any]] = {}
        for inst in svc.instances():
            if instance_id and inst.id != instance_id:
                continue
            result, _ = svc.render(inst)
            folder, _error = svc.folder_for(inst)
            prefix = folder or f"{svc.config.target_dir}/{inst.out_dir}"
            for item in result.files:
                files[f"{prefix}/{item['path']}"] = (inst.id, str(item.get("content") or ""))
            meta[inst.id] = {
                "id": inst.id,
                "template": inst.template,
                "version": result.version,
                "dir": prefix,
                "errors": result.errors,
            }
        return files, meta, list(svc.config.errors)

    base_files, base_meta, base_errors = outputs(base_root)
    head_files, head_meta, head_errors = outputs(head_root)
    entries = diff_files({k: v[1] for k, v in head_files.items()}, {k: v[1] for k, v in base_files.items()})
    by_instance: dict[str, dict[str, int]] = {}
    for entry in entries:
        entry["status"] = COMPARE_STATUS[entry["status"]]
        owner = (head_files.get(entry["path"]) or base_files.get(entry["path"]) or ("?", ""))[0]
        entry["instance"] = owner
        bucket = by_instance.setdefault(owner, {"added": 0, "removed": 0, "modified": 0, "unchanged": 0})
        bucket[entry["status"]] += 1
    instances = []
    for inst_id in sorted(set(base_meta) | set(head_meta)):
        counts = by_instance.get(inst_id, {"added": 0, "removed": 0, "modified": 0, "unchanged": 0})
        if inst_id not in base_meta:
            status = "added"
        elif inst_id not in head_meta:
            status = "removed"
        elif counts["added"] or counts["removed"] or counts["modified"] or base_meta[inst_id]["version"] != head_meta[inst_id]["version"]:
            status = "modified"
        else:
            status = "unchanged"
        info = head_meta.get(inst_id) or base_meta[inst_id]
        instances.append({**info, "status": status, "counts": counts, "base_version": (base_meta.get(inst_id) or {}).get("version")})
    counts = {key: sum(1 for e in entries if e["status"] == key) for key in ("added", "removed", "modified", "unchanged")}
    return {"files": entries, "instances": instances, "counts": counts, "errors": {"base": base_errors, "head": head_errors}}


def count_status(entries: Iterable[dict[str, Any]]) -> dict[str, int]:
    counts = {"new": 0, "modified": 0, "unchanged": 0, "orphaned": 0}
    for entry in entries:
        counts[entry["status"]] = counts.get(entry["status"], 0) + 1
    return counts


