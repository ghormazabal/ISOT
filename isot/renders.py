def make_env(files: dict[str, str]):
    """Entorno sandbox con StrictUndefined. `{% include %}`/`{% import %}` solo ven
    los archivos del propio template."""
    import jinja2
    from jinja2.sandbox import SandboxedEnvironment

    def load(name: str):
        if name not in files:
            return None
        return files[name], name, lambda: True

    env = SandboxedEnvironment(
        loader=jinja2.FunctionLoader(load),
        undefined=jinja2.StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        autoescape=False,
    )
    env.filters.update(FILTERS)
    return env


def _error_info(exc: BaseException, default_file: str, known: Iterable[str] = ()) -> dict[str, Any]:
    """Archivo, línea y tipo de un error de Jinja (sintaxis, variable indefinida, sandbox…)."""
    import jinja2
    from jinja2.exceptions import SecurityError

    if isinstance(exc, jinja2.TemplateSyntaxError):
        return {
            "file": exc.name or exc.filename or default_file,
            "line": exc.lineno,
            "kind": "syntax",
            "message": exc.message or str(exc),
        }
    names = set(known) | {default_file}
    file, line = default_file, None
    for frame in traceback.extract_tb(exc.__traceback__):
        if frame.filename in names:
            file, line = frame.filename, frame.lineno
    if isinstance(exc, jinja2.UndefinedError):
        kind = "undefined"
    elif isinstance(exc, SecurityError):
        kind = "sandbox"
    elif isinstance(exc, RenderError):
        kind = "render"
    else:
        kind = "runtime"
    return {"file": file, "line": line, "kind": kind, "message": str(exc) or exc.__class__.__name__}


