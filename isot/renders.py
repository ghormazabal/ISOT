KIND_ALIASES = {"virtual-machines": "vm", "vms": "vm"}


def _text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _list(value: Any) -> list[Any]:
    if value is None or value == "":
        return []
    if isinstance(value, (list, tuple)):
        return list(value)
    return [value]


def _int_or(value: Any) -> Any:
    try:
        return int(value)
    except (TypeError, ValueError):
        return value


def _vlan(value: Any) -> Any:
    return _int_or(value) if value not in (None, "") else None


def _subnet_dict(raw: dict[str, Any]) -> dict[str, Any]:
    cidr = _text(raw.get("cidr"))
    prefix = netmask = None
    if cidr:
        try:
            net = ipaddress.ip_network(cidr, strict=False)
            prefix, netmask = net.prefixlen, str(net.netmask)
        except ValueError:
            pass
    return {
        "name": _text(raw.get("name")),
        "cidr": cidr,
        "prefix": prefix,
        "netmask": netmask,
        "vlan": _vlan(raw.get("vlan")),
        "gateway": _text(raw.get("gateway")),
        "vrf": _text(raw.get("vrf")),
        "mtu": raw.get("mtu"),
        "description": _text(raw.get("description")),
    }


def _site_dict(site: Any, topology: dict[str, Any]) -> dict[str, Any]:
    block = topology.get("site") if isinstance(topology.get("site"), dict) else {}
    subnets = [_subnet_dict(item) for item in topology.get("subnets") or [] if isinstance(item, dict)]
    vlans = [
        {"id": _int_or(item.get("id")), "name": _text(item.get("name")), "subnet": _text(item.get("subnet"))}
        for item in topology.get("vlans") or []
        if isinstance(item, dict) and item.get("id") not in (None, "")
    ]
    return {
        "id": site.id,
        "name": site.name,
        "description": site.description or _text(block.get("description")),
        "operator": _text(block.get("operator")),
        "domain": _text(block.get("domain")),
        "infra_range": _text(block.get("infra_range")),
        "vlan_range": _text(block.get("vlan_range")),
        "dns_servers": [str(x) for x in _list(block.get("dns_servers"))],
        "dns_search": [str(x) for x in _list(block.get("dns_search"))],
        "ntp_servers": [str(x) for x in _list(block.get("ntp_servers"))],
        "http_proxy": _text(block.get("http_proxy")),
        "https_proxy": _text(block.get("https_proxy")) or _text(block.get("http_proxy")),
        "no_proxy": _text(block.get("no_proxy")),
        "subnets": subnets,
        "vlans": vlans,
    }


def _device_dict(device: Any, subnets_by_vlan: dict[Any, dict[str, Any]]) -> dict[str, Any]:
    data = device.data if isinstance(device.data, dict) else {}
    interfaces = []
    for raw in data.get("networking") or []:
        if not isinstance(raw, dict):
            continue
        addr, prefix = _split_ip(raw.get("ip"))
        vlan = _vlan(raw.get("vlan"))
        subnet = (subnets_by_vlan.get(vlan) if vlan is not None else None) or {}
        connected = raw.get("connected_to") if isinstance(raw.get("connected_to"), dict) else None
        interfaces.append(
            {
                "name": _text(raw.get("interface") or raw.get("name")),
                "parent": _text(raw.get("parent")),
                "vlan": vlan,
                "ip": _text(raw.get("ip")),
                "address": addr,
                "prefix": prefix if prefix is not None else subnet.get("prefix"),
                "gateway": _text(raw.get("gateway")),
                "network": _text(raw.get("network")),
                "subnet": subnet.get("name"),
                "subnet_cidr": subnet.get("cidr"),
                "nad": _text(raw.get("nad")),
                "mtu": raw.get("mtu"),
                "mac": _text(raw.get("mac")),
                "connected_to": (
                    {"device": _text(connected.get("device")), "port": _text(connected.get("port"))} if connected else None
                ),
            }
        )
    bonds = []
    for raw in data.get("bonds") or []:
        if not isinstance(raw, dict):
            continue
        leaf_pc = raw.get("leaf_pc") if isinstance(raw.get("leaf_pc"), dict) else {}
        bonds.append(
            {
                "name": _text(raw.get("name")),
                "mode": _text(raw.get("mode")),
                "mtu": raw.get("mtu"),
                "members": [str(x) for x in _list(raw.get("members") or raw.get("interfaces"))],
                "allowed_vlans": sorted(expand_vlans(raw.get("allowed_vlans"))),
                "extra_host_vlans": sorted(expand_vlans(raw.get("extra_host_vlans"))),
                "leaf_pc": {str(k): (None if v is None else str(v)) for k, v in leaf_pc.items()},
                "note": _text(raw.get("note")),
            }
        )
    labels = data.get("labels") if isinstance(data.get("labels"), dict) else {}
    oob = data.get("oob") if isinstance(data.get("oob"), dict) else None
    hypervisor = data.get("hypervisor") if isinstance(data.get("hypervisor"), dict) else None
    kind = str(_text(data.get("kind")) or device.kind)
    return {
        "hostname": device.hostname,
        "name": device.hostname.lower(),
        "site": device.site_id,
        "role": device.role,
        "kind": KIND_ALIASES.get(kind, kind),
        "k8s_roles": [str(x) for x in _list(data.get("k8s_roles"))],
        "cluster": device.cluster_ref,
        "os": device.os,
        "vendor": device.vendor,
        "model": device.model,
        "labels": {str(k): v for k, v in labels.items()},
        "bonds": bonds,
        "interfaces": interfaces,
        "oob": {"type": _text(oob.get("type")), "ip": _text(oob.get("ip"))} if oob else None,
        "primary_ip": device.primary_ip,
        "hypervisor": redact(hypervisor) if hypervisor else None,
        "resources": redact(data.get("resources")) if isinstance(data.get("resources"), dict) else None,
        "path": device.rel_path,
        "raw": redact(data),
    }


def _cluster_dict(
    ctx: Any, cluster: dict[str, Any], subnets: dict[str, dict[str, Any]], devices: list[dict[str, Any]]
) -> dict[str, Any]:
    name = str(cluster.get("cluster_name") or cluster.get("_stem") or "")
    nads = []
    for raw in cluster.get("nads") or []:
        if not isinstance(raw, dict):
            continue
        subnet = subnets.get(str(raw.get("subnet") or "")) or {}
        nads.append(
            {
                "namespace": _text(raw.get("namespace")),
                "name": _text(raw.get("name")),
                "type": _text(raw.get("type")),
                "master": _text(raw.get("master")),
                "bridge": _text(raw.get("bridge")),
                "vlan": _vlan(raw.get("vlan")),
                "mtu": raw.get("mtu"),
                "ipam": _text(raw.get("ipam")),
                "subnet": _text(raw.get("subnet")),
                "cidr": subnet.get("cidr"),
                "gateway": subnet.get("gateway"),
            }
        )
    metallb = cluster.get("metallb") if isinstance(cluster.get("metallb"), dict) else {}
    pools = [
        {
            "name": _text(raw.get("name")),
            "addresses": [str(x) for x in _list(raw.get("addresses"))],
            "auto_assign": raw.get("autoAssign", raw.get("auto_assign")),
            "subnet": _text(raw.get("subnet")),
            "l2_interfaces": [str(x) for x in _list(raw.get("l2_interfaces"))],
        }
        for raw in metallb.get("pools") or []
        if isinstance(raw, dict)
    ]
    services = metallb.get("services") if isinstance(metallb.get("services"), dict) else {}
    vips = [str(x) for x in _list(metallb.get("vips"))] + [str(v) for v in services.values() if v]
    helm_values: dict[str, Any] = {}
    if cluster.get("kind") == "kubernetes":
        try:
            from isot.rules.k8s import _cluster_values

            helm_values = redact(_cluster_values(ctx, cluster))
        except Exception:  # noqa: BLE001 - values ilegibles no rompen el contexto
            helm_values = {}
    hostnames = {
        str(n.get("hostname")).lower() for n in cluster.get("nodes") or [] if isinstance(n, dict) and n.get("hostname")
    }
    members = [d for d in devices if d["cluster"] == name or d["hostname"].lower() in hostnames]
    vms = [
        d
        for d in devices
        if d["kind"] == "vm" and isinstance(d.get("hypervisor"), dict) and str(d["hypervisor"].get("cluster") or "") == name
    ]
    nodes = [
        {
            "hostname": _text(raw.get("hostname")),
            "k8s_name": _text(raw.get("k8s_name")) or (_text(raw.get("hostname")) or "").lower() or None,
            "roles": [str(x) for x in _list(raw.get("roles"))],
            "internal_ip": _text(raw.get("internal_ip")),
        }
        for raw in cluster.get("nodes") or []
        if isinstance(raw, dict)
    ]
    return {
        "name": name,
        "site": str(cluster.get("_site") or ""),
        "kind": _text(cluster.get("kind")),
        "distro": _text(cluster.get("distro")),
        "version": _text(cluster.get("version")),
        "template_ref": _text(cluster.get("template_ref")),
        "pod_cidr": _text(cluster.get("pod_cidr")),
        "service_cidr": _text(cluster.get("service_cidr")),
        "cni": redact(cluster.get("cni")) if cluster.get("cni") is not None else None,
        "nads": nads,
        "metallb": {
            "version": _text(metallb.get("version")),
            "mode": _text(metallb.get("mode")),
            "pools": pools,
            "services": {str(k): str(v) for k, v in services.items()},
        },
        "vips": vips,
        "nodes": nodes,
        "members": [d["hostname"] for d in members],
        "namespaces": [str(x) for x in _list(cluster.get("namespaces_relevant") or cluster.get("namespaces"))],
        "helm_values": helm_values,
        "vms": vms,
        "path": _text(cluster.get("_path")),
        "raw": redact({k: v for k, v in cluster.items() if not str(k).startswith("_")}),
    }


class ContextBuilder:
    """Construye (y cachea por sitio) el contexto de render a partir de un RuleContext."""

    def __init__(self, ctx: Any) -> None:
        self.ctx = ctx
        self._sites: dict[str, dict[str, Any]] = {}

    def site_ids(self) -> list[str]:
        return [site.id for site in self.ctx.sites]

    def site(self, site_id: str) -> dict[str, Any]:
        if site_id in self._sites:
            return self._sites[site_id]
        site = self.ctx.site(site_id)
        if site is None:
            raise RenderError(f"sitio desconocido: {site_id}")
        site_d = _site_dict(site, self.ctx.topologies.get(site_id) or {})
        by_vlan = {s["vlan"]: s for s in site_d["subnets"] if s["vlan"] is not None}
        by_name = {s["name"]: s for s in site_d["subnets"] if s["name"]}
        devices = sorted(
            (_device_dict(d, by_vlan) for d in self.ctx.devices if d.site_id == site_id), key=lambda d: d["hostname"]
        )
        clusters = sorted(
            (_cluster_dict(self.ctx, c, by_name, devices) for c in self.ctx.clusters if str(c.get("_site") or "") == site_id),
            key=lambda c: c["name"],
        )
        data = {
            "site": site_d,
            "subnets": site_d["subnets"],
            "vlans": site_d["vlans"],
            "devices": devices,
            "clusters": clusters,
            "vms": [d for d in devices if d["kind"] == "vm"],
        }
        self._sites[site_id] = data
        return data

    def variables(
        self,
        site_id: str,
        cluster: str | None,
        *,
        params: dict[str, Any] | None = None,
        instance: dict[str, Any] | None = None,
        template: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Variables que ve un template (ver docs/llm/RENDERS.md)."""
        data = self.site(site_id)
        chosen = None
        devices = data["devices"]
        if cluster:
            chosen = next((c for c in data["clusters"] if c["name"] == cluster), None)
            if chosen is None:
                raise RenderError(f"clúster desconocido en {site_id}: {cluster}")
            names = set(chosen["members"])
            devices = [d for d in data["devices"] if d["hostname"] in names]
        by_name = {s["name"]: s for s in data["subnets"] if s["name"]}
        by_vlan = {s["vlan"]: s for s in data["subnets"] if s["vlan"] is not None}
        by_host = {d["hostname"].lower(): d for d in data["devices"]}

        def subnet(name: Any) -> dict[str, Any] | None:
            return by_name.get(str(name))

        def subnet_by_vlan(vlan: Any) -> dict[str, Any] | None:
            return by_vlan.get(_int_or(vlan))

        def device(hostname: Any) -> dict[str, Any] | None:
            return by_host.get(str(hostname).lower())

        return {
            "context_version": CONTEXT_VERSION,
            "site": data["site"],
            "subnets": data["subnets"],
            "vlans": data["vlans"],
            "site_devices": data["devices"],
            "devices": devices,
            "clusters": data["clusters"],
            "cluster": chosen,
            "vms": chosen["vms"] if chosen else data["vms"],
            "params": copy.deepcopy(params or {}),
            "instance": instance or {},
            "template": template or {},
            "subnet": subnet,
            "subnet_by_vlan": subnet_by_vlan,
            "device": device,
        }

    def explorer(self, site_id: str, cluster: str | None = None) -> dict[str, Any]:
        """Variables serializables (sin funciones) para el explorador de contexto de la UI."""
        data = self.variables(site_id, cluster)
        return {k: v for k, v in data.items() if not callable(v)}


