@dataclass
class TemplateDef:
    id: str
    source: str  # "repo" | "bundled" | "bundled-overridden" | "draft"
    path: str  # relativo al repo de datos, o `@isot/manifests/<id>`
    spec_text: str
    files: dict[str, str]
    spec: dict[str, Any] = field(default_factory=dict)
    errors: list[dict[str, Any]] = field(default_factory=list)

    @property
    def version(self) -> str:
        value = self.spec.get("version")
        return str(value) if value is not None else "1"

    @property
    def scope(self) -> str:
        return str(self.spec.get("scope") or "site")

    def summary(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "source": self.source,
            "path": self.path,
            "version": self.version,
            "description": self.spec.get("description"),
            "scope": self.scope,
            "tags": [str(x) for x in _list(self.spec.get("tags"))],
            "outputs": [
                {"template": o.get("template"), "mode": o.get("mode"), "path": o.get("path")}
                for o in self.spec.get("outputs") or []
            ],
            "files": sorted(self.files),
            "errors": self.errors,
            "params": self.spec.get("params") or {},
        }

    def detail(self) -> dict[str, Any]:
        return {**self.summary(), "spec_text": self.spec_text, "file_contents": dict(self.files)}


def parse_template(template_id: str, spec_text: str, files: dict[str, str], *, source: str, path: str) -> TemplateDef:
    """Valida template.yaml + archivos; los problemas quedan en `errors` (con línea si se puede)."""
    errors: list[dict[str, Any]] = []

    def err(message: str, line: int | None = None) -> None:
        errors.append({"file": TEMPLATE_FILE, "line": line, "kind": "spec", "message": message})

    spec: dict[str, Any] = {}
    try:
        loaded = yaml.safe_load(spec_text) if spec_text.strip() else {}
        if loaded is None:
            loaded = {}
        if isinstance(loaded, dict):
            spec = loaded
        else:
            err("template.yaml debe ser un mapa YAML")
    except yaml.YAMLError as exc:
        mark = getattr(exc, "problem_mark", None)
        err(f"YAML inválido: {getattr(exc, 'problem', None) or exc}", (mark.line + 1) if mark else None)
    for key in sorted(set(spec) - TEMPLATE_KEYS):
        err(f"clave desconocida en template.yaml: {key}")
    declared = spec.get("id")
    if declared is not None and str(declared) != template_id:
        err(f"id={declared!r} no coincide con la carpeta {template_id!r}")
    if not SAFE_ID.fullmatch(template_id):
        err(f"id inválido: {template_id!r} (minúsculas, números, . _ -)")
    scope = str(spec.get("scope") or "site")
    if scope not in SCOPES:
        err(f"scope={scope!r} inválido (site | cluster | device)")
    if spec.get("params") is not None and not isinstance(spec.get("params"), dict):
        err("params debe ser un mapa nombre: valor por defecto")
    outputs = spec.get("outputs")
    if outputs is None and isinstance(spec.get("output"), dict):
        outputs = [spec["output"]]
    if outputs is None:
        outputs = []
        err("falta outputs: [{template, mode, path}]")
    if not isinstance(outputs, list):
        err("outputs debe ser una lista")
        outputs = []
    clean: list[dict[str, Any]] = []
    for index, raw in enumerate(outputs):
        where = f"outputs[{index}]"
        if not isinstance(raw, dict):
            err(f"{where} debe ser un mapa")
            continue
        for key in sorted(set(raw) - OUTPUT_KEYS):
            err(f"{where}: clave desconocida {key}")
        name = str(raw.get("template") or "")
        if not name:
            err(f"{where}: falta template (archivo .j2)")
        elif name not in files:
            err(f"{where}: no existe el archivo {name}")
        mode = str(raw.get("mode") or "single")
        if mode not in MODES:
            err(f"{where}: mode={mode!r} inválido (single | per_item)")
        if not str(raw.get("path") or "").strip():
            err(f"{where}: falta path (ruta de salida; admite Jinja, p.ej. netplan/{{{{ item.name }}}}.yaml)")
        if mode == "per_item" and not (raw.get("for_each") or spec.get("for_each")) and scope != "device":
            err(f"{where}: per_item necesita for_each (o scope: device)")
        clean.append({**raw, "template": name, "mode": mode})
    for name in files:
        if not SAFE_FILE.fullmatch(name) or name == TEMPLATE_FILE:
            err(f"nombre de archivo inválido: {name}")
    spec = {**spec, "outputs": clean, "scope": scope}
    return TemplateDef(template_id, source, path, spec_text, dict(files), spec, errors)


def _read_template_dir(folder: Path, template_id: str, source: str, rel: str) -> TemplateDef:
    spec_path = folder / TEMPLATE_FILE
    spec_text = spec_path.read_text(encoding="utf-8") if spec_path.is_file() and not spec_path.is_symlink() else ""
    files: dict[str, str] = {}
    for child in sorted(folder.iterdir()):
        if child.name == TEMPLATE_FILE or child.name.startswith(".") or child.is_symlink() or not child.is_file():
            continue
        if child.stat().st_size > MAX_SOURCE_BYTES:
            continue
        try:
            files[child.name] = child.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
    return parse_template(template_id, spec_text, files, source=source, path=rel)


def bundled_dir() -> Path:
    return bundled_templates_dir() / BUNDLED_SUBDIR


def repo_templates_dir(root: Path) -> Path:
    return root / TEMPLATE_DIRNAME


def _template_folders(base: Path) -> list[Path]:
    if not base.is_dir():
        return []
    return [
        p
        for p in sorted(base.iterdir())
        if p.is_dir() and not p.is_symlink() and not p.name.startswith((".", "_")) and SAFE_ID.fullmatch(p.name)
    ]


def list_templates(root: Path) -> list[TemplateDef]:
    """Templates del repo de datos y de la herramienta (el del repo gana si comparten id)."""
    out: list[TemplateDef] = []
    seen: set[str] = set()
    for folder in _template_folders(repo_templates_dir(root)):
        out.append(_read_template_dir(folder, folder.name, "repo", f"{TEMPLATE_DIRNAME}/{folder.name}"))
        seen.add(folder.name)
    for folder in _template_folders(bundled_dir()):
        item = _read_template_dir(folder, folder.name, "bundled", f"@isot/{BUNDLED_SUBDIR}/{folder.name}")
        if folder.name in seen:
            item.source = "bundled-overridden"
        out.append(item)
    return out


def find_template(root: Path, template_id: str, source: str | None = None) -> TemplateDef | None:
    """Template por id: primero el del repo de datos, luego el de la herramienta."""
    if not SAFE_ID.fullmatch(template_id or ""):
        return None
    if source in (None, "repo"):
        folder = repo_templates_dir(root) / template_id
        if folder.is_dir() and not folder.is_symlink():
            return _read_template_dir(folder, template_id, "repo", f"{TEMPLATE_DIRNAME}/{template_id}")
        if source == "repo":
            return None
    folder = bundled_dir() / template_id
    if folder.is_dir():
        return _read_template_dir(folder, template_id, "bundled", f"@isot/{BUNDLED_SUBDIR}/{template_id}")
    return None


