def _split_ip(value: Any) -> tuple[str | None, int | None]:
    if value in (None, ""):
        return None, None
    text = str(value).strip()
    if "/" in text:
        addr, _, prefix = text.partition("/")
        try:
            return addr, int(prefix)
        except ValueError:
            return addr, None
    return text, None


def f_ip_address(value: Any) -> str | None:
    """`10.0.0.5/24` → `10.0.0.5`."""
    return _split_ip(value)[0]


def f_prefixlen(value: Any) -> int | None:
    """`10.0.0.5/24` o `10.0.0.0/24` → `24`."""
    return _split_ip(value)[1]


def f_netmask(value: Any) -> str | None:
    try:
        return str(ipaddress.ip_network(str(value), strict=False).netmask)
    except ValueError:
        return None


def f_network(value: Any) -> str | None:
    try:
        return str(ipaddress.ip_network(str(value), strict=False))
    except ValueError:
        return None


def f_with_prefix(address: Any, cidr: Any) -> str | None:
    """`10.0.0.5 | with_prefix('10.0.0.0/24')` → `10.0.0.5/24`."""
    addr = f_ip_address(address)
    if not addr:
        return None
    try:
        return f"{addr}/{ipaddress.ip_network(str(cidr), strict=False).prefixlen}"
    except ValueError:
        return addr


def _plain(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_plain(v) for v in value]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


def f_to_yaml(value: Any, indent: int = 2) -> str:
    return yaml.safe_dump(
        _plain(value), sort_keys=False, allow_unicode=True, default_flow_style=False, indent=indent
    ).rstrip("\n")


def f_to_json(value: Any, indent: int | None = None) -> str:
    return json.dumps(_plain(value), indent=indent, ensure_ascii=False)


def f_flatten(value: Any) -> list[Any]:
    out: list[Any] = []
    for item in value or []:
        if isinstance(item, (list, tuple)):
            out.extend(f_flatten(item))
        else:
            out.append(item)
    return out


def f_explode(value: Any, attribute: str) -> list[dict[str, Any]]:
    """Un elemento por cada `x` de `item[attribute]`: `{"parent": item, "value": x}`.

    Útil para `per_item` por interfaz: `devices | explode('interfaces')`.
    """
    out: list[dict[str, Any]] = []
    for parent in value or []:
        children = parent.get(attribute) if isinstance(parent, dict) else None
        for child in children or []:
            out.append({"parent": parent, "value": child})
    return out


def expand_vlans(value: Any) -> set[int]:
    """`[2000, "2001-2003"]` o `"2000-2002,2010"` → conjunto de VLANs."""
    if value is None or value == "":
        return set()
    items: Iterable[Any] = value if isinstance(value, (list, tuple, set)) else str(value).split(",")
    out: set[int] = set()
    for item in items:
        text = str(item).strip()
        if not text:
            continue
        if "-" in text:
            lo, _, hi = text.partition("-")
            try:
                a, b = int(lo), int(hi)
            except ValueError:
                continue
            if 0 < a <= b <= 4094:
                out.update(range(a, b + 1))
            continue
        try:
            out.add(int(text))
        except ValueError:
            continue
    return out


def f_vlan_list(value: Any) -> list[int]:
    return sorted(expand_vlans(value))


def f_regex_replace(value: Any, pattern: str, repl: str = "") -> str:
    return re.sub(pattern, repl, str(value))


