def test_syntax_error_and_sandbox(data_repo: Path) -> None:
    broken = draft({"outputs": [{"template": "a.j2", "path": "a.yaml"}]}, {"a.j2": "x: {{ site.name \n"})
    result = render_template(broken, builder(data_repo), site="site1")
