def test_single_mode_gets_items_and_per_item_one_file_each(data_repo: Path) -> None:
    template = draft(
        {
            "scope": "site",
            "for_each": "devices | selectattr('kind', 'equalto', 'baremetal') | list",
            "outputs": [
                {"template": "one.j2", "mode": "per_item", "path": "per/{{ item.name }}.txt"},
                {"template": "all.j2", "mode": "single", "path": "all.txt"},
            ],
        },
        {"one.j2": "{{ item.hostname }}\n", "all.j2": "{% for d in items %}{{ d.hostname }}\n{% endfor %}"},
    )
    result = render_template(template, builder(data_repo), site="site1")
    assert result.ok, result.errors
    per = [f for f in result.files if f["path"].startswith("per/")]
    single = next(f for f in result.files if f["path"] == "all.txt")
    assert len(per) >= 2
    assert all(f["mode"] == "per_item" for f in per)
    assert len([line for line in single["content"].splitlines() if line and not line.startswith("#")]) == len(per)


