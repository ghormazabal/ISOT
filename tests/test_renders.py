GIT_ID = ["-c", "user.name=ISoT Test", "-c", "user.email=test@example.net"]


def git(repo: Path, *args: str) -> str:
    proc = subprocess.run(["git", "-C", str(repo), *GIT_ID, *args], check=True, capture_output=True, text=True)
    return proc.stdout.strip()


def git_repo(path: Path) -> Path:
    subprocess.run(["git", "init", "-q", "-b", "main", str(path)], check=True)
    git(path, "config", "user.name", "ISoT Test")
    git(path, "config", "user.email", "test@example.net")
    git(path, "add", "-A")
    git(path, "commit", "-qm", "init", "--allow-empty")
    return path


@pytest.fixture
def data_repo(tmp_path: Path) -> Path:
    """Copia de la demo fuera de la instalación de ISoT, con git."""
    root = tmp_path / "data"
    shutil.copytree(demo_repo_dir(), root)
    return git_repo(root)


def builder(root: Path) -> ContextBuilder:
    return ContextBuilder(load_context(root))


def draft(spec: dict, files: dict[str, str], template_id: str = "t") -> object:
    return parse_template(template_id, yaml.safe_dump({"id": template_id, **spec}), files, source="draft", path="(test)")


