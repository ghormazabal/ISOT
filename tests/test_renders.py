def test_diff_statuses() -> None:
    entries = diff_files(
        {"a.yaml": "1\n", "b.yaml": "2\n", "c.yaml": "3\n", SIDECAR: "{}"},
        {"a.yaml": "1\n", "b.yaml": "old\n", "z.yaml": "hand-made\n", "nested/x.yaml": "other instance\n", SIDECAR: "{}"},
        nested=["nested"],
    )
    status = {e["path"]: e["status"] for e in entries}
    assert status == {"a.yaml": "unchanged", "b.yaml": "modified", "c.yaml": "new", "z.yaml": "orphaned"}
    assert "-old" in next(e for e in entries if e["path"] == "b.yaml")["diff"]


